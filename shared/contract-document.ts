import type { ShopContractDraftData } from "@shared/contract-draft";
import type { IncotermCode } from "@shared/incoterms";

export type ContractDocumentItem = {
  productId: number | string;
  productName: string;
  maxQuantity: number | string;
  unitPrice: number | string;
};

export type ContractDocumentContext = {
  customerName: string;
  contractNumber: string;
  deliveryTerm: IncotermCode | null;
  items: ContractDocumentItem[];
};

const filled = (text: string | number | undefined | null) => String(text ?? "").trim() || "[تکمیل نشده]";

export function buildContractDraftText(draft: ShopContractDraftData, context: ContractDocumentContext): string {
  const customer = filled(context.customerName);
  const seller = draft.seller;
  const buyer = draft.buyer;
  const lines = context.items.map((item) => {
    const details = draft.productDetails[String(item.productId)];
    return `• ${item.productName}: حداکثر ${filled(item.maxQuantity)} واحد، قیمت توافقی هر واحد ${filled(item.unitPrice)} دینار عراق؛ گرید/استاندارد: ${filled(details?.grade)}؛ تلورانس مجاز: ${filled(details?.tolerance)}٪؛ بسته‌بندی/حمل: ${filled(details?.packaging)}.`;
  });
  const law = draft.dealType === "iran"
    ? `این قرارداد تابع قوانین جمهوری اسلامی ایران است. اختلافات ابتدا از طریق مذاکره و در صورت عدم توافق ظرف ۳۰ روز، از طریق داوری اتاق بازرگانی ایران یا مراجع قضایی صالح در ${filled(draft.disputeCity)} حل‌وفصل می‌شود.`
    : draft.dealType === "iraq"
      ? `این قرارداد تابع قوانین توافقی طرفین (ایران/عراق) است. اختلافات ابتدا از طریق مذاکره و در صورت عدم توافق از طریق داوری تجاری در ${filled(draft.disputeCity)} حل‌وفصل می‌شود؛ رأی داوری قطعی و لازم‌الاجراست.`
      : `این قرارداد تابع قوانین کشور توافقی طرفین است. هرگونه اختلاف نهایتاً از طریق داوری مطابق آیین داوری اتاق بازرگانی بین‌المللی (ICC) در ${filled(draft.disputeCity)} حل‌وفصل خواهد شد؛ رأی داوری قطعی است.`;
  const days = filled(draft.payment.days);
  const payment = draft.payment.method === "lc"
    ? `پرداخت از طریق گشایش اعتبار اسنادی غیرقابل برگشت به نفع فروشنده ظرف ${days} روز پیش از بارگیری صورت می‌گیرد.`
    : draft.payment.method === "tt"
      ? `پرداخت از طریق حواله بانکی (TT) ظرف ${days} روز از تاریخ صدور فاکتور به حساب اعلامی فروشنده انجام می‌شود.`
      : draft.payment.method === "credit"
        ? `پرداخت به‌صورت اعتباری/مدت‌دار ظرف ${days} روز پس از تحویل، همراه با تضمین بانکی مورد قبول فروشنده صورت می‌گیرد.`
        : `پیش‌پرداخت ظرف ${days} روز از امضای قرارداد و مانده ثمن هم‌زمان با/پس از تحویل پرداخت می‌شود.`;
  return `قرارداد فروش محصولات پتروشیمی
شماره قرارداد: ${filled(context.contractNumber)}
تاریخ: ${filled(draft.date)}    زبان متن: فارسی

مقدمه و طرفین
این قرارداد میان فروشنده: ${filled(seller.name)} (شناسه: ${filled(seller.registration)}، آدرس: ${filled(seller.address)}، نماینده: ${filled(seller.representative)}، تماس: ${filled(seller.contact)})
و خریدار: ${customer} (کشور: ${filled(buyer.country)}، شناسه: ${filled(buyer.registration)}، آدرس: ${filled(buyer.address)}، نماینده: ${filled(buyer.representative)}، تماس: ${filled(buyer.contact)})
منعقد می‌گردد.

ماده ۱ - تعاریف: محصول، محموله، روز کاری، گواهی تحلیل (COA)، بازرس مستقل و اینکوترمز به شرح مصطلح تجاری و فنی این صنعت تعریف می‌شوند.

ماده ۲ - موضوع قرارداد: فروش و انتقال مالکیت محصولات زیر از فروشنده به خریدار طبق شرایط این قرارداد:
${lines.length ? lines.join("\n") : "[محصولی انتخاب نشده است]"}

ماده ۳ - کیفیت: مشخصات فنی و تلورانس هر محصول مطابق فهرست ماده ۲ است. فروشنده گواهی تحلیل (COA) ارائه می‌کند؛ خریدار حق بازرسی مستقل پیش از بارگیری را دارد.

ماده ۴ - مقدار و بسته‌بندی: سقف تعداد و نحوه بسته‌بندی/حمل هر محصول در ماده ۲ درج شده است. سقف تعداد، حداکثر مقدار مجاز در این قرارداد است و سفارش‌های قبلی از آن کسر می‌شوند.

ماده ۵ - قیمت: قیمت توافقی هر واحد به دینار عراق در ماده ۲ درج شده است؛ نحوه محاسبه و تعدیل طبق پیوست قیمت مورد توافق طرفین خواهد بود.

ماده ۶ - پرداخت: ${payment} تأخیر در پرداخت مشمول خسارت تأخیر تأدیه توافقی خواهد بود.

ماده ۷ - تحویل و حمل: اینکوترم ${filled(context.deliveryTerm || undefined)}؛ محل تحویل: ${filled(draft.delivery.location)}؛ تاریخ تحویل: ${filled(draft.delivery.date)}. تأخیر غیرموجه مشمول خسارت تأخیر تحویل است.

ماده ۸ - انتقال مالکیت و ریسک: هم‌زمان با تحویل طبق اینکوترم منتخب یا تسویه کامل ثمن (هرکدام توافق شود) منتقل می‌گردد.

ماده ۹ - بیمه: در معاملات CIF/CIP بیمه حمل بر عهده فروشنده و به نفع خریدار تحصیل می‌شود؛ در غیر این صورت بر عهده طرف دارای ریسک است.

ماده ۱۰ - بازرسی و اعلام ایراد: خریدار موظف است ظرف مهلت توافقی از دریافت محموله، ایرادات را کتباً اعلام کند.

ماده ۱۱ و ۱۲ - تعهدات طرفین: فروشنده متعهد به تحویل منطبق با مشخصات و اسناد کامل؛ خریدار متعهد به پرداخت به‌موقع، اخذ مجوزهای گمرکی و رعایت مقررات ایمنی و تحریمی است.

ماده ۱۳ - ضمانت و سلب مسئولیت: مسئولیت فروشنده محدود به انطباق با مشخصات فنی توافقی و سقف مبلغ فاکتور محموله معیوب است.

ماده ۱۴ - فورس ماژور: هیچ طرف در قبال تأخیر ناشی از جنگ، تحریم، بلایای طبیعی یا اختلال زیرساختی خارج از کنترل خود مسئول نیست، مشروط به اطلاع‌رسانی کتبی به‌موقع.

ماده ۱۵ - تحریم‌ها و انطباق قانونی: طرفین تضمین می‌کنند در فهرست تحریمی مراجع ذی‌ربط قرار ندارند و در صورت بروز محدودیت تحریمی پس از انعقاد، با حسن نیت راهکار جایگزین را بررسی می‌کنند.

ماده ۱۶ - محرمانگی: اطلاعات تجاری و قیمتی مبادله‌شده محرمانه تلقی و افشای آن به ثالث ممنوع است.

ماده ۱۷ و ۱۸ - خسارت قراردادی و فسخ: نقض تعهدات زمان‌بندی/کیفیت مشمول خسارت توافقی است؛ نقض اساسی و عدم رفع آن پس از اخطار، حق فسخ ایجاد می‌کند.

ماده ۱۹ - قانون حاکم و حل اختلاف: ${law}

ماده ۲۰ - زبان قرارداد: فارسی؛ در صورت اختلاف تفسیر، نسخه فارسی ملاک است.

ماده ۲۱ تا ۲۳ - عدم واگذاری، اطلاعیه‌ها و کامل بودن قرارداد: بدون رضایت کتبی طرف مقابل قابل واگذاری نیست؛ مکاتبات کتبی به آدرس اعلامی معتبر است؛ این سند ناسخ توافقات قبلی است.

ماده ۲۴ - بازبینی و امضا: این متن پیش‌نویس است و پیش از امضا نیازمند بازبینی و تأیید طرفین است. هیچ امضای الکترونیکی یا اثر حقوقی امضا از طریق این متن مفروض نیست.

ماده ۲۵ - وضعیت امضا: در انتظار بازبینی و امضای طرفین.

امضای فروشنده: ${filled(seller.representative)}          امضای خریدار: ${filled(buyer.representative)}
تاریخ: ${filled(draft.date)}`;
}