CREATE FUNCTION guard_customer_type_code_setting() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Customer code settings must be retained'; END IF;
  IF NEW.customer_type<>OLD.customer_type OR NEW.next_number<OLD.next_number
    THEN RAISE EXCEPTION 'Customer identifier counters cannot be renamed or reset'; END IF;
  IF OLD.next_number>1 AND NEW.digit IS DISTINCT FROM OLD.digit
    THEN RAISE EXCEPTION 'A customer type digit cannot change after identifiers have been issued'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER guard_customer_type_code_setting BEFORE UPDATE OR DELETE ON customer_type_code_settings
  FOR EACH ROW EXECUTE FUNCTION guard_customer_type_code_setting();
CREATE FUNCTION assign_customer_business_code() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE cfg customer_type_code_settings;
BEGIN
  IF TG_OP='UPDATE' AND OLD.customer_code IS NOT NULL THEN
    IF NEW.customer_code IS DISTINCT FROM OLD.customer_code THEN RAISE EXCEPTION 'Issued customer identifiers are immutable'; END IF;
    -- Classification may change without replacing an established identity.
    RETURN NEW;
  END IF;
  IF NEW.customer_code IS NOT NULL THEN RAISE EXCEPTION 'Customer identifiers are generated by the system'; END IF;
  SELECT * INTO cfg FROM customer_type_code_settings WHERE customer_type=NEW.customer_type FOR UPDATE;
  IF cfg.digit IS NULL THEN RETURN NEW; END IF;
  IF cfg.next_number>99999 THEN RAISE EXCEPTION 'Customer identifier prefix capacity exhausted'; END IF;
  NEW.customer_code:='9'||cfg.digit||lpad(cfg.next_number::text,5,'0');
  UPDATE customer_type_code_settings SET next_number=next_number+1 WHERE customer_type=cfg.customer_type;
  RETURN NEW;
END $$;
CREATE TRIGGER assign_customer_business_code BEFORE INSERT OR UPDATE ON crm_customers
  FOR EACH ROW EXECUTE FUNCTION assign_customer_business_code();
