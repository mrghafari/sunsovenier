CREATE TABLE customer_type_code_settings (
  customer_type text PRIMARY KEY,
  digit text CHECK(digit IS NULL OR digit ~ '^[0-9]$'),
  next_number integer NOT NULL DEFAULT 1 CHECK(next_number BETWEEN 1 AND 100000),
  CONSTRAINT customer_type_code_settings_digit_key UNIQUE(digit) DEFERRABLE INITIALLY IMMEDIATE
);
